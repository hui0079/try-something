package codecat

import java.awt.Color
import java.awt.Graphics2D
import java.awt.image.BufferedImage
import javax.imageio.ImageIO

object CatSprites {
    const val FRAME_SIZE = 16
    const val DRAW_SIZE = 32
    const val COLUMNS = 6

    private val palette = mapOf(
        '.' to 0x00000000,
        'O' to 0xFF3A1C0A.toInt(),
        'o' to 0xFFE07A30.toInt(),
        'd' to 0xFFC45A18.toInt(),
        'c' to 0xFFF4D4A8.toInt(),
        'e' to 0xFF1A0A00.toInt(),
        'p' to 0xFFE88888.toInt(),
        'w' to 0xFFFFF8EE.toInt(),
    )

    private val sheet: BufferedImage by lazy { loadOrBuild() }

    fun frame(pose: CatPose, walkFrame: Int): BufferedImage {
        val index = when (pose) {
            CatPose.SIT -> 0
            CatPose.WALK -> 1 + (walkFrame and 1)
            CatPose.SLEEP -> 3
            CatPose.STARTLE -> 4
            CatPose.HAPPY -> 5
        }
        return sheet.getSubimage(index * FRAME_SIZE, 0, FRAME_SIZE, FRAME_SIZE)
    }

    fun placeholder(g: Graphics2D, x: Int, y: Int) {
        g.color = Color(0xE07A30)
        g.fillRect(x, y, DRAW_SIZE, DRAW_SIZE)
        g.color = Color(0x3A1C0A)
        g.drawRect(x, y, DRAW_SIZE - 1, DRAW_SIZE - 1)
    }

    private fun loadOrBuild(): BufferedImage {
        val resource = CatSprites::class.java.getResource("/sprites/cat.png")
        if (resource != null) {
            return ImageIO.read(resource)
        }
        return buildSheet()
    }

    internal fun buildSheet(): BufferedImage {
        val image = BufferedImage(FRAME_SIZE * COLUMNS, FRAME_SIZE, BufferedImage.TYPE_INT_ARGB)
        frames().forEachIndexed { index, frame ->
            drawFrame(image, index, frame)
        }
        return image
    }

    private fun drawFrame(sheet: BufferedImage, index: Int, frame: String) {
        val rows = frame.lines()
        for (y in 0 until FRAME_SIZE) {
            val row = rows.getOrNull(y) ?: continue
            for (x in 0 until FRAME_SIZE) {
                val ch = row.getOrElse(x) { '.' }
                val argb = palette[ch] ?: 0
                if (argb != 0) {
                    sheet.setRGB(index * FRAME_SIZE + x, y, argb)
                }
            }
        }
    }

