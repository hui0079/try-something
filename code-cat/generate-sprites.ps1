$bmp = New-Object System.Drawing.Bitmap 96, 16, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$index = 0
foreach ($art in @($sit, $walk1, $walk2, $sleep, $startle, $happy)) {
    $lines = $art.Trim().Replace("`r", "").Split("`n")
    for ($y = 0; $y -lt 16; $y++) {
        $row = $lines[$y]
        for ($x = 0; $x -lt 16; $x++) {
            $ch = $row[$x]
            if ($palette.ContainsKey($ch)) {
                $bmp.SetPixel($index * 16 + $x, $y, $palette[$ch])
            }
        }
    }
    $index++
}

$dir = Join-Path $PSScriptRoot "src\main\resources\sprites"
New-Item -ItemType Directory -Force -Path $dir | Out-Null
$path = Join-Path $dir "cat.png"
$bmp.Save($path, [System.Drawing.Imaging.ImageFormat]::Png)
$bmp.Dispose()
Write-Output $path
